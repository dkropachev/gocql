const (
	cqlPath         = "github.com/scylladb/gocql/v2/cql"
	netipPath       = "net/netip"
	generatedHeader = "// Code generated by cqlgen. DO NOT EDIT."
)

type sourceFile struct {
	file *ast.File
	name string
	test bool
}

type structType struct {
	src  *sourceFile
	name string
}

// importRef is a package a source file refers to by name.
type importRef struct {
	path, pkgName string // pkgName: the package's own name
}

type genField struct {
	column, goName string
	typeSrc        string // the field type as the source spells it
	encoderSrc     string
	decoderSrc     string
	streamSrc      string // empty when the field has no streaming decoder
}

// builtinType is a table entry with its type resolved by go/types.
type builtinType struct {
	typ types.Type
	codec.BuiltinFieldType
}

// generator type-checks one package and maps its structs with the table
// reflection uses. Types are matched by identity, as reflection matches
// reflect.Types, so an alias of cql.UUID maps like cql.UUID and a type
// defined from it does not.
type generator struct {
	fset     *token.FileSet
	info     *types.Info
	pkg      *types.Package
	files    []*ast.File
	names    map[string]bool // every built-in codec and decoder name
	imports  map[string]importRef
	cqlName  string
	builtins []builtinType
	streams  []builtinType
}

// generate returns the output file name and source mapping typeNames, which
// are struct types declared in the package in dir.
func generate(dir string, typeNames []string) (string, []byte, error) {
	fset := token.NewFileSet()
	files, err := parseDir(fset, dir)
	if err != nil {
		return "", nil, err
	}
	var structs []structType
	for _, name := range typeNames {
		name = strings.TrimSpace(name)
		s, err := findStruct(files, name)
		if err != nil {
			return "", nil, err
		}
		if len(structs) > 0 && s.src.file.Name.Name != structs[0].src.file.Name.Name {
			return "", nil, fmt.Errorf("types %s and %s are in different packages", structs[0].name, name)
		}
		structs = append(structs, s)
	}
	if len(structs) == 0 {
		return "", nil, fmt.Errorf("no types given")
	}
	withTests := false
	for _, s := range structs {
		withTests = withTests || s.src.test
	}
	g, err := newGenerator(fset, dir, packageFiles(files, structs[0].src.file.Name.Name, withTests))
	if err != nil {
		return "", nil, err
	}

	var body bytes.Buffer
	for _, s := range structs {
		fields, buffered, stream, err := g.structFields(s)
		if err != nil {
			return "", nil, err
		}
		writeRegistration(&body, s.name, g.cqlName, fields, buffered, stream)
	}

	var out bytes.Buffer
	fmt.Fprintf(&out, "%s\n\npackage %s\n\nimport (\n", generatedHeader, structs[0].src.file.Name.Name)
	names := make([]string, 0, len(g.imports))
	for name := range g.imports {
		names = append(names, name)
	}
	// Standard library first, then the rest, each sorted by path, as goimports does.
	std := func(path string) bool { return !strings.Contains(strings.Split(path, "/")[0], ".") }
	sort.Slice(names, func(i, j int) bool {
		a, b := g.imports[names[i]].path, g.imports[names[j]].path
		if std(a) != std(b) {
			return std(a)
		}
		return a < b
	})
	for i, name := range names {
		ref := g.imports[name]
		if i > 0 && std(g.imports[names[i-1]].path) && !std(ref.path) {
			out.WriteString("\n")
		}
		if ref.pkgName == name {
			fmt.Fprintf(&out, "\t%q\n", ref.path)
		} else {
			fmt.Fprintf(&out, "\t%s %q\n", name, ref.path)
		}
	}
	out.WriteString(")\n\nfunc init() {\n")
	out.Write(body.Bytes())
	out.WriteString("}\n")
	src, err := format.Source(out.Bytes())
	if err != nil {
		return "", nil, fmt.Errorf("formatting output: %w\n%s", err, out.Bytes())
	}
	return outputName(structs[0].src.name), src, nil
}

func outputName(file string) string {
	if base, ok := strings.CutSuffix(file, "_test.go"); ok {
		return base + "_cql_test.go"
	}
	return strings.TrimSuffix(file, ".go") + "_cql.go"
}

func parseDir(fset *token.FileSet, dir string) ([]*sourceFile, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	var files []*sourceFile
	for _, e := range entries {
		if e.IsDir() || !strings.HasSuffix(e.Name(), ".go") {
			continue
		}
		f, err := parser.ParseFile(fset, filepath.Join(dir, e.Name()), nil, parser.ParseComments|parser.SkipObjectResolution)
		if err != nil {
			return nil, err
		}
		if isCqlgenOutput(f) {
			continue
		}
		files = append(files, &sourceFile{name: e.Name(), file: f, test: strings.HasSuffix(e.Name(), "_test.go")})
	}
	return files, nil
}

// packageFiles returns the files type-checked together with package pkg:
// its test files too when a mapped struct is declared in one.
func packageFiles(files []*sourceFile, pkg string, withTests bool) []*ast.File {
	var out []*ast.File
	for _, f := range files {
		if f.file.Name.Name == pkg && (withTests || !f.test) {
			out = append(out, f.file)
		}
	}
	return out
}

func isCqlgenOutput(f *ast.File) bool {
	return len(f.Comments) > 0 && f.Comments[0].Pos() < f.Package &&
		strings.HasPrefix(f.Comments[0].List[0].Text, generatedHeader)
}

func findStruct(files []*sourceFile, name string) (structType, error) {
	for _, f := range files {
		for _, decl := range f.file.Decls {
			gen, ok := decl.(*ast.GenDecl)
			if !ok || gen.Tok != token.TYPE {
				continue
			}
			for _, spec := range gen.Specs {
				ts := spec.(*ast.TypeSpec)
				if ts.Name.Name != name {
					continue
				}
				if ts.TypeParams != nil {
					return structType{}, fmt.Errorf("type %s: generic structs are not supported", name)
				}
				if _, ok := ts.Type.(*ast.StructType); !ok || ts.Assign.IsValid() {
					return structType{}, fmt.Errorf("type %s is not a struct type definition", name)
				}
				return structType{name: name, src: f}, nil
			}
		}
	}
	return structType{}, fmt.Errorf("type %s not found", name)
}

// newGenerator type-checks files against the compiled export data of their
// imports, which go list builds into the build cache.
func newGenerator(fset *token.FileSet, dir string, files []*ast.File) (*generator, error) {
	exports, err := exportData(dir)
	if err != nil {
		return nil, err
	}
	imp := importer.ForCompiler(fset, "gc", func(path string) (io.ReadCloser, error) {
		file, ok := exports[path]
		if !ok || file == "" {
			return nil, fmt.Errorf("no export data for %s", path)
		}
		return os.Open(file)
	})
	info := &types.Info{
		Types:     map[ast.Expr]types.TypeAndValue{},
		Defs:      map[*ast.Ident]types.Object{},
		Uses:      map[*ast.Ident]types.Object{},
		Implicits: map[ast.Node]types.Object{},
	}
	var errs []string
	conf := types.Config{Importer: imp, Error: func(err error) {
		if len(errs) < 10 {
			errs = append(errs, err.Error())
		}
	}}
	pkg, err := conf.Check(files[0].Name.Name, fset, files, info)
	if err != nil && len(errs) > 0 {
		return nil, fmt.Errorf("type-checking:\n\t%s", strings.Join(errs, "\n\t"))
	}

	// Resolve the table's type spellings in a scope that names cql and netip.
	scratch := types.NewPackage("cqlgen/table", "table")
	for name, path := range map[string]string{"cql": cqlPath, "netip": netipPath} {
		pkg, err := imp.Import(path)
		if err != nil {
			return nil, err
		}
		scratch.Scope().Insert(types.NewPkgName(token.NoPos, scratch, name, pkg))
	}
	g := &generator{fset: fset, info: info, pkg: pkg, files: files, names: map[string]bool{}, imports: map[string]importRef{}}
	resolve := func(table []codec.BuiltinFieldType) ([]builtinType, error) {
		out := make([]builtinType, len(table))
		for i, b := range table {
			tv, err := types.Eval(token.NewFileSet(), scratch, token.NoPos, b.TypeSrc)
			if err != nil {
				return nil, fmt.Errorf("built-in type %s: %w", b.TypeSrc, err)
			}
			out[i] = builtinType{BuiltinFieldType: b, typ: types.Unalias(tv.Type)}
			for _, n := range b.Names {
				g.names[n] = true
			}
		}
		return out, nil
	}
	if g.builtins, err = resolve(codec.BuiltinFieldTypes()); err != nil {
		return nil, err
	}
	if g.streams, err = resolve(codec.StreamBuiltinFieldTypes()); err != nil {
		return nil, err
	}
	g.cqlName = "cql"
	for _, f := range files {
		for _, spec := range f.Imports {
			if pkg := info.PkgNameOf(spec); pkg != nil && pkg.Imported().Path() == cqlPath {
				g.cqlName = pkg.Name()
			}
		}
	}
	if prev, ok := g.imports[g.cqlName]; ok && prev.path != cqlPath {
		return nil, fmt.Errorf("package name %s refers to %s, not %s", g.cqlName, prev.path, cqlPath)
	}
	g.imports[g.cqlName] = importRef{path: cqlPath, pkgName: "cql"}
	return g, nil
}

// exportData maps import paths to export data files for the package in dir,
// its tests and the packages the table names.
func exportData(dir string) (map[string]string, error) {
	cmd := exec.Command("go", "list", "-e", "-export", "-deps", "-test",
		"-f", "{{.ImportPath}}\t{{.Export}}", ".", cqlPath, netipPath)
	cmd.Dir = dir
	var stderr bytes.Buffer
	cmd.Stderr = &stderr
	out, err := cmd.Output()
	if err != nil {
		return nil, fmt.Errorf("go list: %w\n%s", err, stderr.Bytes())
	}
	exports := map[string]string{}
	scanner := bufio.NewScanner(bytes.NewReader(out))
	for scanner.Scan() {
		path, file, _ := strings.Cut(scanner.Text(), "\t")
		if strings.Contains(path, " [") { // a test variant; the plain package is listed too
			continue
		}
		exports[path] = file
	}
	return exports, scanner.Err()
}

// structFields maps s's fields, and those of the structs it embeds by value,
// with the rules reflection applies (codec.EmbeddedField and
// codec.ResolveFieldConflicts). The buffered mapping (Params and Columns) and
// the streaming one are each generated only when every field has a codec for
// it; a struct neither covers is an error, as is a wrong `codec=` or
// `stream=` tag.
func (g *generator) structFields(s structType) (_ []genField, buffered, stream bool, _ error) {
	st := g.pkg.Scope().Lookup(s.name).Type().Underlying().(*types.Struct)
	type found struct {
		v    *types.Var
		tag  codec.FieldTag
		path string
	}
	var fields []found
	var candidates []codec.FieldCandidate
	var walk func(st *types.Struct, prefix string, depth int) error
	walk = func(st *types.Struct, prefix string, depth int) error {
		for i := range st.NumFields() {
			v, tag := st.Field(i), reflect.StructTag(st.Tag(i))
			path := prefix + v.Name()
			if v.Embedded() {
				t := types.Unalias(v.Type())
				_, pointer := t.(*types.Pointer)
				inner, isStruct := t.Underlying().(*types.Struct)
				embed, err := codec.EmbeddedField(v.Name(), tag, pointer, isStruct)
				if err != nil {
					return fmt.Errorf("%s: %w", s.name, err)
				}
				if embed == codec.EmbedSkip {
					continue
				}
				if embed == codec.EmbedFlatten {
					if err := walk(inner, path+".", depth+1); err != nil {
						return err
					}
					continue
				}
			}
			ft, ok, err := codec.ParseFieldTag(v.Name(), v.Exported(), tag)
			if err != nil {
				return fmt.Errorf("%s: %w", s.name, err)
			}
			if ok {
				fields = append(fields, found{v: v, tag: ft, path: path})
				candidates = append(candidates, codec.FieldCandidate{Column: ft.Column, Path: path, Depth: depth})
			}
		}
		return nil
	}
	if err := walk(st, "", 0); err != nil {
		return nil, false, false, err
	}
	keep, err := codec.ResolveFieldConflicts(candidates)
	if err != nil {
		return nil, false, false, fmt.Errorf("%s: %w", s.name, err)
	}

	var out []genField
	buffered, stream = true, true
	var bufferedErr error
	for _, i := range keep {
		v, ft, where := fields[i].v, fields[i].tag, s.name+"."+fields[i].path
		if err := g.nameable(v.Type()); err != nil {
			return nil, false, false, fmt.Errorf("%s: %w", where, err)
		}
		f := genField{column: ft.Column, goName: fields[i].path, typeSrc: types.TypeString(v.Type(), g.qualifier)}
		// A codec expression is written in the scope of the field's file,
		// which only this package's own files share with the output.
		var file *ast.File
		if v.Pkg() == g.pkg {
			file = g.fileOf(v.Pos())
		}
		enc, dec, ok, err := g.codec(file, g.builtins, v.Type(), ft.Codec, "codec")
		if err != nil {
			return nil, false, false, fmt.Errorf("%s: %w", where, err)
		}
		if ok {
			f.encoderSrc, f.decoderSrc = enc, dec
		} else if buffered {
			buffered = false
			bufferedErr = fmt.Errorf("%s: no codec for type %s; add a `codec=` tag", where, f.typeSrc)
		}
		_, streamDec, ok, err := g.codec(file, g.streams, v.Type(), ft.Stream, "stream")
		if err != nil {
			return nil, false, false, fmt.Errorf("%s: %w", where, err)
		}
		if ok {
			f.streamSrc = streamDec
		} else {
			stream = false
		}
		out = append(out, f)
	}
	if !buffered && !stream {
		return nil, false, false, bufferedErr
	}
	return out, buffered, stream, nil
}

// nameable reports a type the output cannot spell: one unexported from
// another package, which an embedded struct can bring in.
func (g *generator) nameable(t types.Type) error {
	switch t := t.(type) {
	case *types.Alias:
		if obj := t.Obj(); obj.Pkg() != nil && obj.Pkg() != g.pkg && !obj.Exported() {
			return fmt.Errorf("type %s is not exported from %s", obj.Name(), obj.Pkg().Path())
		}
		for arg := range t.TypeArgs().Types() {
			if err := g.nameable(arg); err != nil {
				return err
			}
		}
	case *types.Named:
		if obj := t.Obj(); obj.Pkg() != nil && obj.Pkg() != g.pkg && !obj.Exported() {
			return fmt.Errorf("type %s is not exported from %s", obj.Name(), obj.Pkg().Path())
		}
		for arg := range t.TypeArgs().Types() {
			if err := g.nameable(arg); err != nil {
				return err
			}
		}
	case *types.Pointer:
		return g.nameable(t.Elem())
	case *types.Slice:
		return g.nameable(t.Elem())
	case *types.Array:
		return g.nameable(t.Elem())
	case *types.Map:
		if err := g.nameable(t.Key()); err != nil {
			return err
		}
		return g.nameable(t.Elem())
	}
	return nil
}

// qualifier names the packages in the output's type spellings, importing
// those the output does not import yet.
func (g *generator) qualifier(p *types.Package) string {
	if p == g.pkg {
		return ""
	}
	names := make([]string, 0, len(g.imports))
	for name := range g.imports {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		if g.imports[name].path == p.Path() {
			return name
		}
	}
	name := p.Name()
	for n := 2; ; n++ {
		if _, taken := g.imports[name]; !taken {
			break
		}
		name = p.Name() + strconv.Itoa(n)
	}
	g.imports[name] = importRef{path: p.Path(), pkgName: p.Name()}
	return name
}

func (g *generator) fileOf(pos token.Pos) *ast.File {
	for _, f := range g.files {
		if f.FileStart <= pos && pos <= f.FileEnd {
			return f
		}
	}
	return nil
}

// codec picks a field's codec source from table: a built-in named by the tag,
// else the tag's own Go expression, else the type's built-in default.
func (g *generator) codec(file *ast.File, table []builtinType, typ types.Type, tag, key string) (enc, dec string, found bool, err error) {
	var candidates []codec.BuiltinFieldType
	for _, b := range table {
		if types.Identical(types.Unalias(typ), b.typ) {
			candidates = append(candidates, b.BuiltinFieldType)
		}
	}
	if i, ok := codec.SelectBuiltin(candidates, tag); ok {
		return g.qualify(candidates[i].EncoderSrc), g.qualify(candidates[i].DecoderSrc), true, nil
	}
	if tag == "" {
		return "", "", false, nil
	}
	if g.names[tag] {
		return "", "", false, fmt.Errorf("%s %q is not a built-in for %s", key, tag, types.TypeString(typ, nil))
	}
	if file == nil {
		return "", "", false, fmt.Errorf("%s %q: a codec expression on a field of a struct from another package cannot be resolved here; use WithCodec or generate in that package", key, tag)
	}
	expr, err := parser.ParseExpr(tag)
	if err != nil {
		return "", "", false, fmt.Errorf("%s %q: %w", key, tag, err)
	}
	if err := g.useExprImports(file, expr); err != nil {
		return "", "", false, err
	}
	return tag, tag, true, nil
}

// useExprImports records the imports of file that expr names.
func (g *generator) useExprImports(file *ast.File, expr ast.Expr) error {
	byName := map[string]*types.PkgName{}
	for _, spec := range file.Imports {
		if pkg := g.info.PkgNameOf(spec); pkg != nil {
			byName[pkg.Name()] = pkg
		}
	}
	var err error
	ast.Inspect(expr, func(n ast.Node) bool {
		sel, ok := n.(*ast.SelectorExpr)
		if !ok || err != nil {
			return err == nil
		}
		x, ok := sel.X.(*ast.Ident)
		if !ok {
			return true
		}
		pkg, ok := byName[x.Name]
		if !ok {
			return true // a local value, such as a struct-typed codec variable
		}
		ref := importRef{path: pkg.Imported().Path(), pkgName: pkg.Imported().Name()}
		if prev, ok := g.imports[x.Name]; ok && prev.path != ref.path {
			err = fmt.Errorf("package name %s refers to both %s and %s", x.Name, prev.path, ref.path)
			return false
		}
		g.imports[x.Name] = ref
		return true
	})
	return err
}

// qualify spells a table codec with the package name the source uses for cql.
func (g *generator) qualify(src string) string {
	if g.cqlName == "cql" {
		return src
	}
	return strings.ReplaceAll(src, "cql.", g.cqlName+".")
}

func writeRegistration(b *bytes.Buffer, typeName, cql string, fields []genField, buffered, stream bool) {
	fmt.Fprintf(b, "\t%s.RegisterStruct(%s.StructFields[%s]{\n", cql, cql, typeName)
	if buffered {
		fmt.Fprintf(b, "\t\tParams: []%s.InputField[%s]{\n", cql, typeName)
		for _, f := range fields {
			fmt.Fprintf(b, "\t\t\t%s.Param(%q, %s, func(v %s) %s { return v.%s }),\n",
				cql, f.column, f.encoderSrc, typeName, f.typeSrc, f.goName)
		}
		fmt.Fprintf(b, "\t\t},\n\t\tColumns: []%s.OutputField[%s]{\n", cql, typeName)
		for _, f := range fields {
			fmt.Fprintf(b, "\t\t\t%s.Column(%q, %s, func(v *%s) *%s { return &v.%s }),\n",
				cql, f.column, f.decoderSrc, typeName, f.typeSrc, f.goName)
		}
		b.WriteString("\t\t},\n")
	}
	if stream {
		fmt.Fprintf(b, "\t\tStreamColumns: []%s.StreamOutputField[%s]{\n", cql, typeName)
		for _, f := range fields {
			fmt.Fprintf(b, "\t\t\t%s.StreamColumn(%q, %s, func(v *%s) *%s { return &v.%s }),\n",
				cql, f.column, f.streamSrc, typeName, f.typeSrc, f.goName)
		}
		b.WriteString("\t\t},\n")
	}
	b.WriteString("\t})\n")
}
