var update = flag.Bool("update", false, "rewrite the golden files of testdata/builtins")

// builtinsDir holds a package with one field for every entry of the built-in
// field table, its cqlgen output, and a test that checks the output against
// reflection.
var builtinsDir = filepath.Join("testdata", "builtins")

// builtinsSource returns the source of builtins.go: struct Buffered has one
// field for every buffered table entry and Streamed one for every streaming
// entry, selected by its default or by its first codec name.
func builtinsSource() []byte {
	var b bytes.Buffer
	b.WriteString(`// Code generated by TestBuiltins from the built-in field table. DO NOT EDIT.

// Package builtins maps one field of every built-in field type; cqlgen
// generates builtins_cql.go from it, and its test checks that mapping
// against reflection.
package builtins

import (
	"net/netip"

	"github.com/scylladb/gocql/v2/cql"
)

var _ netip.Addr
`)
	for _, s := range []struct {
		name, key, prefix string
		stream            bool
	}{{"Buffered", "codec", "b", false}, {"Streamed", "stream", "s", true}} {
		fmt.Fprintf(&b, "\ntype %s struct {\n", s.name)
		for i, e := range builtinFieldTypes(s.stream) {
			tag := fmt.Sprintf("%s%03d", s.prefix, i)
			if !e.Default {
				tag += "," + s.key + "=" + e.Names[0]
			}
			fmt.Fprintf(&b, "\tF%03d %s `cql:%q` // %s\n", i, e.TypeSrc, tag, e.DecoderSrc)
		}
		b.WriteString("}\n")
	}
	out, err := format.Source(b.Bytes())
	if err != nil {
		panic(err)
	}
	return out
}

// builtinReachable reports whether a field tag selects entry i of the table:
// its default, or its first codec name.
func builtinReachable(stream bool, i int) bool {
	table := builtinFieldTypes(stream)
	var candidates []structmap.BuiltinFieldType
	at := -1
	for j, e := range table {
		if e.Type == table[i].Type {
			if j == i {
				at = len(candidates)
			}
			candidates = append(candidates, e)
		}
	}
	name := ""
	if !table[i].Default {
		name = table[i].Names[0]
	}
	got, ok := structmap.SelectBuiltin(candidates, name)
	return ok && got == at
}

// TestBuiltins checks cqlgen against the whole built-in field table: every
// entry is reachable from a field, the output is the committed golden file,
// and the golden package compiles and maps like reflection. Rewrite the
// golden files with go test ./cmd/cqlgen -run TestBuiltins -update.
func TestBuiltins(t *testing.T) {
	golden := func(t *testing.T, name string, got []byte) {
		t.Helper()
		path := filepath.Join(builtinsDir, name)
		if *update {
			if err := os.WriteFile(path, got, 0o644); err != nil {
				t.Fatal(err)
			}
			return
		}
		want, err := os.ReadFile(path)
		if err != nil {
			t.Fatal(err)
		}
		if !bytes.Equal(got, want) {
			t.Fatalf("%s is stale; run go test ./cmd/cqlgen -run TestBuiltins -update", path)
		}
	}
	// An entry no tag selects is dead for reflection and cqlgen alike.
	t.Run("Reachable", func(t *testing.T) {
		for _, stream := range []bool{false, true} {
			for i, e := range builtinFieldTypes(stream) {
				if !builtinReachable(stream, i) {
					t.Errorf("no tag selects %s for %s", e.DecoderSrc, e.TypeSrc)
				}
			}
		}
	})
	t.Run("Source", func(t *testing.T) { golden(t, "builtins.go", builtinsSource()) })
	t.Run("Generate", func(t *testing.T) {
		name, got, err := generate(builtinsDir, []string{"Buffered", "Streamed"})
		if err != nil {
			t.Fatal(err)
		}
		if name != "builtins_cql.go" {
			t.Fatalf("output name %q", name)
		}
		// Each field must get its own table entry's codec.
		for _, s := range []struct {
			typ, call string
			stream    bool
		}{{"Buffered", "cql.Column", false}, {"Streamed", "cql.StreamColumn", true}} {
			for i, e := range builtinFieldTypes(s.stream) {
				prefix := "b"
				if s.stream {
					prefix = "s"
				}
				want := fmt.Sprintf("%s(%q, %s, func(v *%s) *%s { return &v.F%03d })", s.call, fmt.Sprintf("%s%03d", prefix, i), e.DecoderSrc, s.typ, e.TypeSrc, i)
				if !bytes.Contains(got, []byte(want)) {
					t.Errorf("missing %s", want)
				}
			}
		}
		golden(t, name, got)
	})
	t.Run("Compile", func(t *testing.T) {
		if testing.Short() {
			t.Skip("builds and tests the golden package")
		}
		// go ./... skips testdata, so the package is built and tested here.
		args := []string{"test", "-count=1", "./" + filepath.ToSlash(builtinsDir)}
		if out, err := exec.Command("go", args...).CombinedOutput(); err != nil {
			t.Fatalf("go %s: %v\n%s", strings.Join(args, " "), err, out)
		}
	})
}
