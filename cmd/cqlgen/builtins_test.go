var update = flag.Bool("update", false, "rewrite the golden files of testdata/builtins")

// builtinsDir holds a package with fields of every built-in leaf type and
// the types derived from them, its cqlgen output, and a test that checks the
// output against reflection.
var builtinsDir = filepath.Join("testdata", "builtins")

// builtinField is one field of builtins.go: its type, `codec=` or `stream=`
// tag, and the codec cqlgen derives for it, as a comment.
type builtinField struct {
	typ, tag, src string
}

// derivedShapes returns the buffered fields derived from leaf e, whose type
// and codec are spelled t and c: every one-level form, and for a sample of
// leaves the nested ones.
func derivedShapes(e structmap.BuiltinFieldType) (buffered, bound []builtinField) {
	t, c := e.TypeSrc, e.EncoderSrc
	buffered = []builtinField{
		{t, "", c},
		{"cql.Nullable[" + t + "]", "", "cql.NullableDecoder(" + c + ")"},
		{"[]" + t, "", "cql.SliceCodec(" + c + ")"},
		{"[]" + t, "ListCodec", "cql.ListCodec(" + c + ")"},
		{"[]" + t, "SetCodec", "cql.SetCodec(" + c + ")"},
		{"[]" + t, "VectorCodec", "cql.VectorCodec(" + c + ")"},
	}
	for _, alias := range e.Names[1:] {
		buffered = append(buffered, builtinField{t, alias, c})
	}
	if !strings.HasPrefix(t, "*") {
		buffered = append(buffered, builtinField{"*" + t, "", "cql.PointerCodec(" + c + ")"})
	}
	switch t {
	case "int32", "string", "cql.UUID":
		buffered = append(buffered,
			builtinField{"[][]" + t, "", "cql.SliceCodec(cql.SliceCodec(" + c + "))"},
			builtinField{"map[string][]" + t, "", "cql.GoMapCodec(cql.StringCodec, cql.SliceCodec(" + c + "))"},
			builtinField{"map[" + t + "]" + t, "", "cql.GoMapCodec(" + c + ", " + c + ")"},
			builtinField{"*[]" + t, "", "cql.PointerCodec(cql.SliceCodec(" + c + "))"},
			builtinField{"cql.Nullable[[]" + t + "]", "", "cql.NullableDecoder(cql.SliceCodec(" + c + "))"},
			builtinField{"[]cql.Nullable[" + t + "]", "", "cql.SliceCodec(cql.NullableCodec(" + c + "))"},
			builtinField{"cql.Pair[" + t + ", int64]", "", "cql.PairCodec(" + c + ", cql.Int64Codec)"},
			builtinField{"[2]" + t, "", "cql.ConvertCodec(cql.SliceCodec(" + c + "), ...)"},
		)
	case "time.Time", "time.Duration":
		buffered = append(buffered, builtinField{"map[string]" + t, "", "cql.GoMapCodec(cql.StringCodec, " + c + ")"})
	}
	bound = []builtinField{{"cql.BindValue[" + t + "]", "", "cql.BindEncoder(" + c + ")"}}
	return buffered, bound
}

// builtinsSource returns the source of builtins.go: struct Buffered has the
// fields of derivedShapes for every leaf, Bound a BindValue of every leaf,
// which only binds parameters, and Streamed one for every streaming entry,
// each selected by its default or by its first decoder name.
func builtinsSource() []byte {
	var b bytes.Buffer
	b.WriteString(`// Code generated by TestBuiltins from the built-in field table. DO NOT EDIT.

// Package builtins maps fields of every built-in leaf type and the types
// derived from them; cqlgen generates builtins_cql.go from it, and its test
// checks that mapping against reflection.
package builtins

import (
	"math/big"
	"net/netip"
	"time"

	"github.com/scylladb/gocql/v2/cql"
)

var (
	_ big.Int
	_ netip.Addr
	_ time.Time
)
`)
	var buffered, bound, streamed []builtinField
	for _, e := range builtinFieldTypes(false) {
		f, p := derivedShapes(e)
		buffered, bound = append(buffered, f...), append(bound, p...)
	}
	buffered = append(buffered, builtinField{"[16]byte", "", "cql.UUIDCodec"})
	for _, e := range builtinFieldTypes(true) {
		tag := ""
		if !e.Default {
			tag = e.Names[0]
		}
		streamed = append(streamed, builtinField{e.TypeSrc, tag, e.DecoderSrc})
	}
	for _, s := range []struct {
		name, key, prefix string
		fields            []builtinField
	}{{"Buffered", "codec", "b", buffered}, {"Bound", "codec", "p", bound}, {"Streamed", "stream", "s", streamed}} {
		fmt.Fprintf(&b, "\ntype %s struct {\n", s.name)
		for i, f := range s.fields {
			tag := fmt.Sprintf("%s%03d", s.prefix, i)
			if f.tag != "" {
				tag += "," + s.key + "=" + f.tag
			}
			fmt.Fprintf(&b, "\tF%03d %s `cql:%q` // %s\n", i, f.typ, tag, f.src)
		}
		b.WriteString("}\n")
	}
	out, err := format.Source(b.Bytes())
	if err != nil {
		panic(err)
	}
	return out
}

// builtinReachable reports whether a field tag selects entry i of the table:
// its default, or its first codec name.
func builtinReachable(stream bool, i int) bool {
	table := builtinFieldTypes(stream)
	var candidates []structmap.BuiltinFieldType
	at := -1
	for j, e := range table {
		if e.Type == table[i].Type {
			if j == i {
				at = len(candidates)
			}
			candidates = append(candidates, e)
		}
	}
	name := ""
	if !table[i].Default {
		name = table[i].Names[0]
	}
	got, ok := structmap.SelectBuiltin(candidates, name)
	return ok && got == at
}

// TestBuiltins checks cqlgen against the whole built-in field table: every
// entry is reachable from a field, the output is the committed golden file,
// and the golden package compiles and maps like reflection. Rewrite the
// golden files with go test ./cmd/cqlgen -run TestBuiltins -update.
func TestBuiltins(t *testing.T) {
	golden := func(t *testing.T, name string, got []byte) {
		t.Helper()
		path := filepath.Join(builtinsDir, name)
		if *update {
			if err := os.WriteFile(path, got, 0o644); err != nil {
				t.Fatal(err)
			}
			return
		}
		want, err := os.ReadFile(path)
		if err != nil {
			t.Fatal(err)
		}
		if !bytes.Equal(got, want) {
			t.Fatalf("%s is stale; run go test ./cmd/cqlgen -run TestBuiltins -update", path)
		}
	}
	// An entry no tag selects is dead for reflection and cqlgen alike.
	t.Run("Reachable", func(t *testing.T) {
		for _, stream := range []bool{false, true} {
			for i, e := range builtinFieldTypes(stream) {
				if !builtinReachable(stream, i) {
					t.Errorf("no tag selects %s for %s", e.DecoderSrc, e.TypeSrc)
				}
			}
		}
	})
	t.Run("Source", func(t *testing.T) { golden(t, "builtins.go", builtinsSource()) })
	t.Run("Generate", func(t *testing.T) {
		name, got, err := generate(builtinsDir, []string{"Buffered", "Bound", "Streamed"})
		if err != nil {
			t.Fatal(err)
		}
		if name != "builtins_cql.go" {
			t.Fatalf("output name %q", name)
		}
		// Each leaf field must get its own table entry's codec, and each
		// stream field its entry's decoder.
		i := 0
		for _, e := range builtinFieldTypes(false) {
			want := fmt.Sprintf("cql.Column(%q, %s, func(v *Buffered) *%s { return &v.F%03d })", fmt.Sprintf("b%03d", i), e.DecoderSrc, e.TypeSrc, i)
			if !bytes.Contains(got, []byte(want)) {
				t.Errorf("missing %s", want)
			}
			fields, _ := derivedShapes(e)
			i += len(fields)
		}
		for i, e := range builtinFieldTypes(true) {
			want := fmt.Sprintf("cql.StreamColumn(%q, %s, func(v *Streamed) *%s { return &v.F%03d })", fmt.Sprintf("s%03d", i), e.DecoderSrc, e.TypeSrc, i)
			if !bytes.Contains(got, []byte(want)) {
				t.Errorf("missing %s", want)
			}
		}
		golden(t, name, got)
	})
	t.Run("Compile", func(t *testing.T) {
		if testing.Short() {
			t.Skip("builds and tests the golden package")
		}
		// The coverage job compiles every package with -race and
		// -coverpkg=./..., and a nested build of this package beside those
		// compiles outran the test timeout and the runner's memory. Plain
		// unit test runs still build it.
		if testing.CoverMode() != "" {
			t.Skip("builds and tests the golden package; not under -cover")
		}
		// go ./... skips testdata, so the package is built and tested here.
		args := []string{"test", "-count=1", "./" + filepath.ToSlash(builtinsDir)}
		if out, err := exec.Command("go", args...).CombinedOutput(); err != nil {
			t.Fatalf("go %s: %v\n%s", strings.Join(args, " "), err, out)
		}
	})
}
