package cql

import codec "github.com/scylladb/gocql/v2/internal/codec"

// StructOption configures ParamsOf and RowOf.
type StructOption[P any] = codec.StructOption[P]

// StructFields is a struct's complete mapping, as cmd/cqlgen generates it.
type StructFields[P any] = codec.StructFields[P]

// ParamsOf binds a statement's parameters from the exported fields of struct
// P by column name. A field's column is its `cql:"name"` tag, or its
// lowercased name; `cql:"-"` skips it and `cql:"name,codec=ASCIIStringCodec"`
// picks a built-in codec other than the type's default. A field without a
// matching parameter is skipped, so one struct serves statements that bind a
// subset of its columns, but every parameter needs a field. The fields of a
// struct embedded by value map as if declared in P, and an outer field hides
// an embedded one with the same column; embedding by pointer is rejected.
// Slice fields map lists by default (ListCodec; `codec=SetCodec` for sets);
// maps need MapCodec through WithCodec or a `codec=` tag.
//
// A mapping generated by cmd/cqlgen is used when registered; otherwise P is
// reflected once, here. Either way encoding is reflection-free and as fast as
// hand-written Params.
func ParamsOf[P any](opts ...StructOption[P]) (ParamEncoder[P], error) {
	return codec.ParamsOf[P](opts...)
}

// RowOf decodes rows into struct P by column name, mapped like ParamsOf. A
// field whose column is not selected stays zero.
func RowOf[R any](opts ...StructOption[R]) (RowDecoder[R], error) { return codec.RowOf[R](opts...) }

// MustParamsOf is ParamsOf that panics on error, for package-level variables.
func MustParamsOf[P any](opts ...StructOption[P]) ParamEncoder[P] {
	return codec.MustParamsOf[P](opts...)
}

// MustRowOf is RowOf that panics on error, for package-level variables.
func MustRowOf[R any](opts ...StructOption[R]) RowDecoder[R] { return codec.MustRowOf[R](opts...) }

// WithCodec maps P's fields of type V, and of Nullable[V], with c: a type
// with no built-in codec, such as a UDT, or a replacement for V's default.
func WithCodec[P, V any](c Codec[V]) StructOption[P] { return codec.WithCodec[P, V](c) }

// RegisterStruct installs a mapping generated by cmd/cqlgen; generated code
// calls it from init. It panics when P is already registered.
func RegisterStruct[P any](fields StructFields[P]) { codec.RegisterStruct[P](fields) }

// StreamRowOf decodes streamed rows into struct P by column name, mapped like
// RowOf but with the streaming decoders, which have their own Go types: text,
// ascii, blob and varint columns decode into []byte (blob by default; pick
// another with `cql:"name,stream=StreamText"`), and slices decode lists
// (`stream=StreamSet` for sets). Storage of []byte and slice fields is reused
// across rows. Every column needs a field.
func StreamRowOf[R any](opts ...StructOption[R]) (StreamRowDecoder[R], error) {
	return codec.StreamRowOf[R](opts...)
}

// MustStreamRowOf is StreamRowOf that panics on error.
func MustStreamRowOf[R any](opts ...StructOption[R]) StreamRowDecoder[R] {
	return codec.MustStreamRowOf[R](opts...)
}

// WithStreamCodec maps P's fields of type V, Nullable[V] and []V (as a list)
// with decoder in StreamRowOf.
func WithStreamCodec[P, V any](decoder StreamDecoder[V]) StructOption[P] {
	return codec.WithStreamCodec[P, V](decoder)
}

// ReuseBuffers makes RowOf keep the storage of P's []byte fields between rows
// decoded into the same destination, as RowInto does. The next row overwrites
// those bytes, so copy a field that must outlive its row.
func ReuseBuffers[P any]() StructOption[P] { return codec.ReuseBuffers[P]() }

// ListCodec encodes and decodes a list as a []T, the form struct mappings
// use for slice fields. A null cell, how CQL stores an empty list, decodes as
// an empty slice. Decoding allocates the slice unless the destination has the
// capacity (see ReuseBuffers); ListDecoder's lazy Sequence copies nothing.
func ListCodec[T any](element Codec[T]) Codec[[]T] { return codec.ListCodec[T](element) }

// SetCodec is ListCodec for a set; elements keep the order the server sends.
func SetCodec[T any](element Codec[T]) Codec[[]T] { return codec.SetCodec[T](element) }

// MapCodec encodes and decodes a map as a []Entry[K, V], in the order the
// server sends; keys need not be comparable. Struct mappings take it through
// WithCodec or a `codec=` tag, since the type tables have no map entries.
func MapCodec[K, V any](key Codec[K], value Codec[V]) Codec[[]Entry[K, V]] {
	return codec.MapCodec[K, V](key, value)
}
